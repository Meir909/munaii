const STORAGE_PREFIX = "munai_help_seen_";

export function helpStorageKey(featureId: FeatureHelpId, role: Role) {
  return `${STORAGE_PREFIX}${featureId}_${role}`;
}

export function hasSeenFeatureHelp(featureId: FeatureHelpId, role: Role) {
  try {
    return localStorage.getItem(helpStorageKey(featureId, role)) === "1";
  } catch {
    return true;
  }
}

export function markFeatureHelpSeen(featureId: FeatureHelpId, role: Role) {
  try {
    localStorage.setItem(helpStorageKey(featureId, role), "1");
  } catch {
    // ignore
  }
}

export function getFeatureHelp(featureId: FeatureHelpId, role: Role): FeatureHelpContent | null {
  return HELP[featureId]?.[role] ?? HELP[featureId]?.operator ?? null;
}
